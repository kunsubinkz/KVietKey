#!/usr/bin/env python3
"""Sinh src/KVietKey.Engine/CharsetTables.g.cs từ bảng mã của bản macOS.

Nguồn duy nhất: macos/Packages/VietEngine/Sources/VietEngine/Charset/CharsetTables.swift
(do macos/tools/gen_charsets.py tạo ra). Script này chỉ đổi cú pháp Swift → C#, không đổi dữ liệu.

Dùng: python3 tools/gen_charsets_cs.py > src/KVietKey.Engine/CharsetTables.g.cs
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / "../macos/Packages/VietEngine/Sources/VietEngine/Charset/CharsetTables.swift").resolve().read_text(encoding="utf-8")

tables = re.findall(r"static let (\w+): \[\(UInt16, \[UInt8\]\)\] = \[(.*?)\n    \]", src, re.S)
assert len(tables) == 4, [t[0] for t in tables]

out = ["// <auto-generated>",
       "// Sinh bởi tools/gen_charsets_cs.py từ CharsetTables.swift (bản macOS) — không sửa tay.",
       "// </auto-generated>",
       "namespace KVietKey.Engine;",
       "",
       "internal static class CharsetTables",
       "{"]
for name, body in tables:
    rows = re.findall(r"\((0x[0-9A-Fa-f]+), \[([^\]]*)\]\)", body)
    assert rows, name
    out.append(f"    public static readonly (ushort Code, byte[] Bytes)[] {name[0].upper()}{name[1:]} =")
    out.append("    [")
    for code, data in rows:
        out.append(f"        ({code}, [{', '.join(x.strip() for x in data.split(','))}]),")
    out.append("    ];")
    out.append("")
out[-1] = "}"
sys.stdout.write("\n".join(out) + "\n")
